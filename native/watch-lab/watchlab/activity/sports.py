# When a summary has no sport-type field (older layouts), the file id's subtype decides.
SUBTYPE_TO_EXERCISE = {
    0x01: RUNNING, 0x02: WALKING, 0x03: RUNNING_TREADMILL, 0x06: BIKING, 0x07: BIKING_STATIONARY,
    0x08: OTHER, 0x09: SWIM_POOL, 0x10: HIIT, 0x0B: ELLIPTICAL, 0x0D: ROWING_MACHINE, 0x0E: OTHER,
    0x16: WALKING, 0x17: BIKING,
}


def exercise_type(xiaomi_type: int | None, subtype: int) -> int:
    if xiaomi_type:
        return XIAOMI_TO_EXERCISE.get(xiaomi_type, OTHER)
    return SUBTYPE_TO_EXERCISE.get(subtype, OTHER)
